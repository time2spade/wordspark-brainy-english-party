export const KNOWN_NON_NOUNS_SET = new Set<string>(KNOWN_NON_NOUNS);

/**
 * Checks if a word is an inflectional plural of an existing noun
 */
export function checkPluralNounMatch(clean: string): boolean {
  if (clean.length < 3) return false;

  // Irregular plurals (e.g. CHILDREN -> CHILD, TEETH -> TOOTH)
  if (IRREGULAR_NOUN_PLURALS[clean]) {
    const singular = IRREGULAR_NOUN_PLURALS[clean];
    if (EMBEDDED_NOUNS_SET.has(singular)) return true;
  }

  // -IES (e.g. CITIES -> CITY, BABIES -> BABY, PARTIES -> PARTY)
  if (clean.endsWith("IES") && clean.length > 4) {
    const base = clean.slice(0, -3) + "Y";
    if (EMBEDDED_NOUNS_SET.has(base)) return true;
  }

  // -VES (e.g. LEAVES -> LEAF, WOLVES -> WOLF, KNIVES -> KNIFE)
  if (clean.endsWith("VES") && clean.length > 4) {
    if (EMBEDDED_NOUNS_SET.has(clean.slice(0, -3) + "F")) return true;
    if (EMBEDDED_NOUNS_SET.has(clean.slice(0, -3) + "FE")) return true;
  }

  // -ES (e.g. BOXES -> BOX, FOXES -> FOX, WATCHES -> WATCH, DISHES -> DISH, TOMATOES -> TOMATO)
  if (clean.endsWith("ES") && clean.length > 4) {
    if (EMBEDDED_NOUNS_SET.has(clean.slice(0, -2))) return true;
  }

  // -S (e.g. CATS -> CAT, DOGS -> DOG, COMPUTERS -> COMPUTER, STATIONS -> STATION)
  if (clean.endsWith("S") && !clean.endsWith("SS") && clean.length > 3) {
    if (EMBEDDED_NOUNS_SET.has(clean.slice(0, -1))) return true;
  }

  return false;
}
