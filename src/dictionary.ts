/**
 * Validates whether a candidate word fulfills the given constraint.
 */
export function validateConstraint(word: string, constraint: Constraint): { valid: boolean; reason?: string } {
  const clean = word.trim().toUpperCase();

  switch (constraint.type) {
    case 'STARTS_WITH': {
      const req = String(constraint.value).toUpperCase();
      if (!clean.startsWith(req)) {
        return { valid: false, reason: `Word must start with "${req}"` };
      }
      return { valid: true };
    }
    case 'ENDS_WITH': {
      const req = String(constraint.value).toUpperCase();
      if (!clean.endsWith(req)) {
        return { valid: false, reason: `Word must end with "${req}"` };
      }
      return { valid: true };
    }
    case 'CONTAINS': {
      const sub = String(constraint.value).toUpperCase();
      if (!clean.includes(sub)) {
        return { valid: false, reason: `Word must contain "${sub}"` };
      }
      return { valid: true };
    }
    case 'MIN_LENGTH': {
      const min = Number(constraint.value);
      if (clean.length < min) {
        return { valid: false, reason: `Word must have at least ${min} letters (it has ${clean.length})` };
      }
      return { valid: true };
    }
    case 'CATEGORY': {
      const cat = String(constraint.value);
      const list = THEMATIC_CATEGORIES[cat] || [];
      if (!list.includes(clean)) {
        return { valid: false, reason: `"${clean}" is not in the ${cat} topic list!` };
      }
      return { valid: true };
    }
    case 'NO_REPEATED_LETTERS': {
      const chars = clean.split('');
      const unique = new Set(chars);
      if (unique.size !== chars.length) {
        return { valid: false, reason: `Contains repeated letters (e.g. duplicates)!` };
      }
      return { valid: true };
    }
    default:
      return { valid: true };
  }
}

